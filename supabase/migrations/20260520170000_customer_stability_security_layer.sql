create table if not exists public.analytics_events_integrity (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  event_name text not null,
  event_fingerprint text not null,
  payload jsonb not null default '{}'::jsonb,
  status text not null default 'pending'
    check (status in ('pending', 'retry', 'manual_review', 'sent', 'failed')),
  attempts integer not null default 0 check (attempts >= 0),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  next_retry_at timestamptz not null default timezone('utc', now()),
  sent_at timestamptz,
  unique (user_id, event_fingerprint)
);

create index if not exists analytics_events_integrity_user_idx
  on public.analytics_events_integrity (user_id, created_at desc);
create index if not exists analytics_events_integrity_status_idx
  on public.analytics_events_integrity (status, next_retry_at, created_at);

