create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create table if not exists public.order_request_tokens (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  order_request_token text not null,
  checkout_session_id text,
  payment_reference_id text,
  restaurant_id uuid,
  order_id uuid,
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'completed', 'queued_offline', 'failed', 'expired', 'confirmed')),
  payment_method text,
  total_amount numeric(12, 2) not null default 0,
  reconciliation_status text not null default 'pending',
  verification_attempts integer not null default 0 check (verification_attempts >= 0),
  attempts integer not null default 0 check (attempts >= 0),
  last_error text,
  expires_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (user_id, order_request_token)
);

create index if not exists order_request_tokens_user_status_idx
  on public.order_request_tokens (user_id, status, updated_at desc);
create index if not exists order_request_tokens_token_idx
  on public.order_request_tokens (order_request_token);
create index if not exists order_request_tokens_payment_reference_idx
  on public.order_request_tokens (payment_reference_id)
  where payment_reference_id is not null;

drop trigger if exists order_request_tokens_set_updated_at on public.order_request_tokens;
create trigger order_request_tokens_set_updated_at
before update on public.order_request_tokens
for each row
execute function public.set_updated_at();

create table if not exists public.payment_reconciliation_logs (
  id bigint generated by default as identity primary key,
