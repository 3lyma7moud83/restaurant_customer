begin
  v_fingerprint := public.security_hash_text(
    concat_ws('|',
      coalesce(nullif(trim(p_alert_key), ''), 'security_alert'),
      coalesce(nullif(trim(p_subject_kind), ''), 'user'),
      coalesce(nullif(trim(p_subject_value), ''), '-')
    )
  );

  select id into v_existing_id
  from public.security_alerts
  where fingerprint = v_fingerprint and status = 'open'
  limit 1;

  if v_existing_id is not null then
    update public.security_alerts
    set
      occurrences = occurrences + 1,
      last_seen_at = timezone('utc', now()),
      severity = public.normalize_security_severity(p_severity),
      actor_user_id = coalesce(p_actor_user_id, actor_user_id),
      related_event_id = coalesce(p_related_event_id, related_event_id),
      details = coalesce(details, '{}'::jsonb) || coalesce(p_details, '{}'::jsonb),
      updated_at = timezone('utc', now())
    where id = v_existing_id
    returning id into v_id;
    return v_id;
  end if;

  insert into public.security_alerts (
    alert_key,
    severity,
    status,
    actor_user_id,
    subject_kind,
    subject_value,
    related_event_id,
    fingerprint,
    details
  )
  values (
    coalesce(nullif(trim(p_alert_key), ''), 'security_alert'),
    public.normalize_security_severity(p_severity),
    'open',
    p_actor_user_id,
    coalesce(nullif(trim(p_subject_kind), ''), 'user'),
    nullif(trim(coalesce(p_subject_value, '')), ''),
    p_related_event_id,
    v_fingerprint,
    coalesce(p_details, '{}'::jsonb)
  )
  returning id into v_id;

  return v_id;
end;
$$;

