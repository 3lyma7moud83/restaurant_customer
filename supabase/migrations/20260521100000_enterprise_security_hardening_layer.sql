create or replace function public.secure_payment_decision(
  p_payment_reference_id text,
  p_decision text,
  p_reason text,
  p_rpc_request_id text,
  p_rpc_nonce text,
  p_rpc_signature text,
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := auth.uid();
  v_decision text := lower(coalesce(nullif(trim(p_decision), ''), ''));
  v_reason text := coalesce(nullif(trim(p_reason), ''), 'manual_payment_decision');
  v_rows integer := 0;
  v_status text;
begin
  if v_actor is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;
  if not public.is_elevated_security_actor(v_actor) then
    raise exception 'insufficient_privileges' using errcode = '42501';
  end if;
  if coalesce(trim(p_payment_reference_id), '') = '' then
    raise exception 'payment_reference_id_required' using errcode = '22023';
  end if;

  if v_decision not in ('approve', 'approved', 'reject', 'rejected') then
    raise exception 'invalid_payment_decision' using errcode = '22023';
  end if;

  v_status := case when v_decision in ('approve', 'approved') then 'confirmed' else 'failed' end;

  perform public.verify_and_consume_rpc_nonce('secure_payment_decision', 'payment_management', p_rpc_request_id, p_rpc_nonce, p_rpc_signature, jsonb_build_object('payment_reference_id', p_payment_reference_id, 'decision', v_decision, 'reason', v_reason), true, v_actor, p_metadata);
  perform public.enforce_admin_action_rate_limit('payment_decision', 120, 30, 180, 1, p_rpc_request_id, jsonb_build_object('payment_reference_id', p_payment_reference_id));

  if to_regclass('public.order_request_tokens') is not null then
    update public.order_request_tokens
    set
      status = v_status,
      reconciliation_status = case when v_status = 'confirmed' then 'approved' else 'rejected' end,
      last_error = case when v_status = 'failed' then v_reason else null end,
      updated_at = timezone('utc', now())
    where payment_reference_id = trim(p_payment_reference_id);

    get diagnostics v_rows = row_count;
  end if;

  if v_rows = 0 then
    raise exception 'payment_reference_not_found' using errcode = 'P0002';
  end if;

  perform public.record_security_event(case when v_status = 'confirmed' then 'payment_approved' else 'payment_rejected' end, 'high', v_actor, null, null, null, jsonb_build_object('payment_reference_id', trim(p_payment_reference_id), 'decision', v_decision, 'reason', v_reason, 'affected_rows', v_rows) || coalesce(p_metadata, '{}'::jsonb), p_rpc_request_id, p_rpc_nonce);
  perform public.append_immutable_audit('payment_admin_action', case when v_status = 'confirmed' then 'approve_payment' else 'reject_payment' end, 'payment_reference', trim(p_payment_reference_id), jsonb_build_object('reason', v_reason, 'affected_rows', v_rows, 'decision', v_decision), 'admin_payment', v_actor, public.current_security_actor_role());

  return jsonb_build_object('ok', true, 'payment_reference_id', trim(p_payment_reference_id), 'decision', v_decision, 'status', v_status, 'affected_rows', v_rows);
end;
$$;

revoke all on function public.secure_payment_decision(text, text, text, text, text, text, jsonb) from public;
grant execute on function public.secure_payment_decision(text, text, text, text, text, text, jsonb) to authenticated, service_role;

create or replace function public.secure_change_user_role(
  p_target_user_id uuid,
  p_new_role text,
  p_reason text,
  p_rpc_request_id text,
  p_rpc_nonce text,
  p_rpc_signature text,
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := auth.uid();
  v_new_role text := lower(coalesce(nullif(trim(p_new_role), ''), ''));
  v_rows integer := 0;
begin
  if v_actor is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;
  if p_target_user_id is null then
    raise exception 'target_user_id_required' using errcode = '22023';
  end if;
  if v_new_role = '' then
    raise exception 'new_role_required' using errcode = '22023';
  end if;
  if not public.is_elevated_security_actor(v_actor) then
    raise exception 'insufficient_privileges' using errcode = '42501';
  end if;

  perform public.verify_and_consume_rpc_nonce('secure_change_user_role', 'role_management', p_rpc_request_id, p_rpc_nonce, p_rpc_signature, jsonb_build_object('target_user_id', p_target_user_id, 'new_role', v_new_role, 'reason', p_reason), true, v_actor, p_metadata);
  perform public.enforce_admin_action_rate_limit('role_change', 300, 25, 300, 1, p_rpc_request_id, jsonb_build_object('target_user_id', p_target_user_id));

  if to_regclass('public.user_roles') is not null then
    begin
      execute '
        insert into public.user_roles (user_id, role, updated_at)
        values ($1, $2, timezone(''utc'', now()))
        on conflict (user_id)
        do update set role = excluded.role, updated_at = timezone(''utc'', now())'
      using p_target_user_id, v_new_role;
      get diagnostics v_rows = row_count;
    exception
      when others then
        null;
    end;
  end if;

  if v_rows = 0 and to_regclass('public.profiles') is not null then
    begin
      execute '
        update public.profiles
        set role = $1,
            updated_at = timezone(''utc'', now())
        where id = $2'
      using v_new_role, p_target_user_id;
      get diagnostics v_rows = row_count;
    exception
      when others then
        null;
    end;
  end if;

  if v_rows = 0 then
    raise exception 'role_target_table_missing_or_user_not_found' using errcode = 'P0002';
  end if;

  perform public.record_security_event('role_changed', 'high', v_actor, null, null, null, jsonb_build_object('target_user_id', p_target_user_id, 'new_role', v_new_role, 'reason', p_reason, 'affected_rows', v_rows) || coalesce(p_metadata, '{}'::jsonb), p_rpc_request_id, p_rpc_nonce);
  perform public.append_immutable_audit('role_admin_action', 'change_role', 'auth_user', p_target_user_id::text, jsonb_build_object('new_role', v_new_role, 'reason', p_reason, 'affected_rows', v_rows), 'admin_role', v_actor, public.current_security_actor_role());

  return jsonb_build_object('ok', true, 'target_user_id', p_target_user_id, 'new_role', v_new_role, 'affected_rows', v_rows);
end;
$$;

