grant execute on function public.verify_and_consume_rpc_nonce(text, text, text, text, text, jsonb, boolean, uuid, jsonb) to authenticated, service_role;

create or replace function public.enforce_admin_action_rate_limit(
  p_action_key text,
  p_window_seconds integer default 60,
  p_max_actions integer default 20,
  p_cooldown_seconds integer default 120,
  p_weight integer default 1,
  p_request_id text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_action_key text := nullif(trim(p_action_key), '');
  v_now timestamptz := timezone('utc', now());
  v_window_seconds integer := greatest(5, least(coalesce(p_window_seconds, 60), 3600));
  v_max_actions integer := greatest(1, least(coalesce(p_max_actions, 20), 500));
  v_weight integer := greatest(1, least(coalesce(p_weight, 1), 50));
  v_cooldown_seconds integer := greatest(10, least(coalesce(p_cooldown_seconds, 120), 7200));
  v_window_start timestamptz := v_now - make_interval(secs => v_window_seconds);
  v_current_actions integer := 0;
  v_recent_blocks integer := 0;
  v_active_cooldown timestamptz;
  v_allowed boolean := true;
  v_abuse_score integer;
begin
  if v_user_id is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  if v_action_key is null then
    raise exception 'action_key_required' using errcode = '22023';
  end if;

  if not public.is_elevated_security_actor(v_user_id) then
    raise exception 'insufficient_privileges_for_admin_action' using errcode = '42501';
  end if;

  select max(cooldown_until) into v_active_cooldown
  from public.admin_action_limits
  where admin_user_id = v_user_id
    and action_key = v_action_key
    and cooldown_until > v_now;

  if v_active_cooldown is not null then
    v_allowed := false;
  end if;

  select count(*) into v_current_actions
  from public.admin_action_limits
  where admin_user_id = v_user_id
    and action_key = v_action_key
    and allowed = true
    and attempted_at >= v_window_start;

  select count(*) into v_recent_blocks
  from public.admin_action_limits
  where admin_user_id = v_user_id
    and action_key = v_action_key
    and allowed = false
    and attempted_at >= v_now - interval '30 minutes';

  if v_allowed and (v_current_actions + v_weight > v_max_actions) then
    v_allowed := false;
    v_active_cooldown := v_now + make_interval(secs => least(7200, v_cooldown_seconds + (v_recent_blocks * 15)));
  end if;

  v_abuse_score := greatest(0, (v_current_actions + v_weight) - v_max_actions) + v_recent_blocks;

  insert into public.admin_action_limits (
    admin_user_id, action_key, allowed, window_seconds, max_actions, attempted_at, cooldown_until, abuse_score, request_id, metadata
  ) values (
    v_user_id, v_action_key, v_allowed, v_window_seconds, v_max_actions, v_now, v_active_cooldown, v_abuse_score, nullif(trim(coalesce(p_request_id, '')), ''), coalesce(p_metadata, '{}'::jsonb)
  );

  if not v_allowed then
    perform public.record_security_event('admin_action_rate_limited', 'high', v_user_id, null, null, null, jsonb_build_object('action_key', v_action_key, 'cooldown_until', v_active_cooldown, 'abuse_score', v_abuse_score), p_request_id, null);
    perform public.evaluate_security_escalation('user', v_user_id::text, 'admin_action_rate_limited', 'high', jsonb_build_object('action_key', v_action_key, 'abuse_score', v_abuse_score), v_user_id);
    perform public.log_security_metric('abuse_rate', 1, 'admin_rate_limit', v_user_id, jsonb_build_object('action_key', v_action_key, 'cooldown_until', v_active_cooldown, 'abuse_score', v_abuse_score));
  end if;

  return jsonb_build_object(
    'allowed', v_allowed,
    'action_key', v_action_key,
    'current_actions', v_current_actions,
    'max_actions', v_max_actions,
    'cooldown_until', v_active_cooldown,
    'abuse_score', v_abuse_score,
    'remaining', greatest(0, v_max_actions - (v_current_actions + v_weight))
  );
end;
$$;

