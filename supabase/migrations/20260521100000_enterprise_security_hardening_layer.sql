create or replace function public.verify_and_consume_rpc_nonce(
  p_rpc_name text,
  p_action_scope text,
  p_request_id text,
  p_nonce text,
  p_request_signature text,
  p_payload jsonb default '{}'::jsonb,
  p_raise_on_failure boolean default true,
  p_actor_user_id uuid default auth.uid(),
  p_metadata jsonb default '{}'::jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_rpc_name text := nullif(trim(p_rpc_name), '');
  v_action_scope text := coalesce(nullif(trim(p_action_scope), ''), 'default');
  v_request_id text := nullif(trim(p_request_id), '');
  v_nonce text := nullif(trim(p_nonce), '');
  v_signature text := nullif(trim(p_request_signature), '');
  v_payload_hash text := public.security_hash_text(coalesce(p_payload::text, '{}'));
  v_actor_user_id uuid := coalesce(p_actor_user_id, auth.uid());
  v_secret text;
  v_expected_signature text;
  v_now timestamptz := timezone('utc', now());
  v_reason text;
  v_row public.rpc_nonce_registry%rowtype;
begin
  if v_actor_user_id is null then
    if p_raise_on_failure then
      raise exception 'not_authenticated' using errcode = '42501';
    end if;
    return false;
  end if;

  if v_rpc_name is null or v_request_id is null or v_nonce is null or v_signature is null then
    v_reason := 'missing_nonce_arguments';
    perform public.register_replay_attempt(null, v_request_id, v_nonce, v_rpc_name, v_action_scope, v_actor_user_id, v_reason, v_payload_hash, v_signature, p_metadata);
    if p_raise_on_failure then
      raise exception 'rpc_replay_guard_violation:%', v_reason using errcode = '42501';
    end if;
    return false;
  end if;

  select * into v_row
  from public.rpc_nonce_registry
  where request_id = v_request_id
  limit 1;

  if not found then
    v_reason := 'nonce_not_found';
  elsif coalesce(v_row.nonce, '') <> v_nonce then
    v_reason := 'nonce_mismatch';
  elsif coalesce(v_row.rpc_name, '') <> v_rpc_name then
    v_reason := 'rpc_name_mismatch';
  elsif coalesce(v_row.action_scope, '') <> v_action_scope then
    v_reason := 'action_scope_mismatch';
  elsif v_row.actor_user_id is distinct from v_actor_user_id then
    v_reason := 'actor_mismatch';
  elsif v_row.status = 'consumed' then
    v_reason := 'already_consumed';
  elsif v_row.status = 'rejected' then
    v_reason := 'already_rejected';
  elsif v_row.status = 'expired' or v_row.expires_at <= v_now then
    v_reason := 'expired_nonce';
  elsif coalesce(v_row.payload_hash, '') <> v_payload_hash then
    v_reason := 'payload_hash_mismatch';
  end if;

  if v_reason is null then
    select rpc_signature_secret into v_secret from public.security_runtime_config where id = true limit 1;
    if coalesce(v_secret, '') = '' then
      v_secret := public.security_hash_text(v_actor_user_id::text);
    end if;

    v_expected_signature := encode(
      hmac(
        concat_ws('|', v_row.request_id, v_row.nonce, v_row.rpc_name, v_row.action_scope, v_row.actor_user_id::text, v_row.payload_hash, extract(epoch from v_row.expires_at)::bigint::text),
        v_secret,
        'sha256'
      ),
      'hex'
    );

    if v_expected_signature <> v_signature then
      v_reason := 'invalid_signature';
    end if;
  end if;

  if v_reason is not null then
    update public.rpc_nonce_registry
    set
      status = case when v_reason = 'expired_nonce' then 'expired' else 'rejected' end,
      last_seen_at = v_now
    where id = v_row.id;

    perform public.register_replay_attempt(v_row.id, v_request_id, v_nonce, v_rpc_name, v_action_scope, v_actor_user_id, v_reason, v_payload_hash, v_signature, p_metadata);

    if p_raise_on_failure then
      raise exception 'rpc_replay_guard_violation:%', v_reason using errcode = '42501';
    end if;
    return false;
  end if;

  update public.rpc_nonce_registry
  set status = 'consumed', consumed_at = v_now, last_seen_at = v_now
  where id = v_row.id;

  perform public.append_immutable_audit('rpc_nonce_consumed', v_rpc_name, 'rpc', v_rpc_name, jsonb_build_object('request_id', v_request_id, 'nonce', v_nonce, 'action_scope', v_action_scope), 'rpc_guard', v_actor_user_id, public.current_security_actor_role());
  perform public.log_security_metric('rpc_nonce_consumed', 1, 'rpc_replay', v_actor_user_id, jsonb_build_object('rpc_name', v_rpc_name));

  return true;
end;
$$;

