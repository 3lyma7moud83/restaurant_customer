create or replace function public.normalize_security_severity(p_value text)
returns text
language plpgsql
immutable
as $$
declare
  v_value text := lower(coalesce(trim(p_value), 'medium'));
begin
  if v_value in ('low', 'medium', 'high', 'critical') then
    return v_value;
  end if;
  return 'medium';
end;
$$;

create or replace function public.security_hash_text(p_input text)
returns text
language sql
immutable
as $$
  select encode(digest(coalesce($1, ''), 'sha256'), 'hex');
$$;

create or replace function public.current_security_actor_role()
returns text
language plpgsql
stable
as $$
begin
  return lower(
    coalesce(
      nullif(trim(auth.jwt() ->> 'role'), ''),
      nullif(trim(current_setting('request.jwt.claim.role', true)), ''),
      current_user,
      'authenticated'
    )
  );
end;
$$;

create or replace function public.is_elevated_security_actor(
  p_user_id uuid default auth.uid()
)
returns boolean
language plpgsql
stable
as $$
declare
  v_claim_role text := lower(coalesce(auth.jwt() ->> 'role', ''));
  v_app_role text := lower(
    coalesce(
      auth.jwt() -> 'app_metadata' ->> 'role',
      auth.jwt() -> 'user_metadata' ->> 'role',
      ''
    )
  );
begin
  if v_claim_role in ('service_role', 'supabase_admin', 'postgres') then
    return true;
  end if;

  if v_app_role in ('admin', 'owner', 'security_admin', 'super_admin', 'ops_admin') then
    return true;
  end if;

  return false;
end;
$$;

