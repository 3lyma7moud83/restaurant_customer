create or replace function public.evaluate_queue_payload_poison(
  p_queue_name text,
  p_payload jsonb,
  p_attempt_count integer default 0,
  p_last_error text default null,
  p_queue_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_queue_name text := coalesce(nullif(trim(p_queue_name), ''), 'unknown_queue');
  v_payload jsonb := coalesce(p_payload, '{}'::jsonb);
  v_payload_text text := coalesce(v_payload::text, '{}');
  v_payload_hash text := public.security_hash_text(v_payload_text);
  v_bytes integer := length(v_payload_text);
  v_attempts integer := greatest(0, coalesce(p_attempt_count, 0));
  v_last_error text := lower(coalesce(p_last_error, ''));
  v_known_status text;
  v_reason text;
  v_is_poison boolean := false;
  v_retry_cap integer := 8;
begin
  select quarantine_status into v_known_status
  from public.poison_payload_registry
  where queue_name = v_queue_name and payload_hash = v_payload_hash
  order by last_seen_at desc
  limit 1;

  if v_known_status in ('quarantined', 'manual_review') then
    v_is_poison := true;
    v_reason := 'known_poison_payload';
  elsif v_bytes > 65535 then
    v_is_poison := true;
    v_reason := 'oversized_payload';
  elsif v_attempts >= v_retry_cap then
    v_is_poison := true;
    v_reason := 'retry_cap_exceeded';
  elsif v_attempts >= 3 and (
    v_last_error like '%invalid%' or
    v_last_error like '%malformed%' or
    v_last_error like '%json%' or
    v_last_error like '%schema%'
  ) then
    v_is_poison := true;
    v_reason := 'repeated_malformed_payload';
  end if;

  return jsonb_build_object('is_poison', v_is_poison, 'reason', v_reason, 'payload_hash', v_payload_hash, 'known_status', v_known_status, 'retry_cap', v_retry_cap, 'payload_bytes', v_bytes, 'queue_id', p_queue_id);
end;
$$;

