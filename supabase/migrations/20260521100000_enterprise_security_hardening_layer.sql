create or replace function public.prepare_rpc_nonce(
  p_rpc_name text,
  p_action_scope text default 'default',
  p_request_id text default null,
  p_payload jsonb default '{}'::jsonb,
  p_valid_for_seconds integer default 120,
  p_metadata jsonb default '{}'::jsonb
)
returns table (
  request_id text,
  nonce text,
  expires_at timestamptz,
  request_signature text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_rpc_name text := nullif(trim(p_rpc_name), '');
  v_action_scope text := coalesce(nullif(trim(p_action_scope), ''), 'default');
  v_actor_user_id uuid := auth.uid();
  v_request_id text := coalesce(nullif(trim(p_request_id), ''), gen_random_uuid()::text);
  v_nonce text := encode(gen_random_bytes(18), 'hex');
  v_valid_for_seconds integer := greatest(30, least(coalesce(p_valid_for_seconds, 120), 600));
  v_expires_at timestamptz := timezone('utc', now()) + make_interval(secs => v_valid_for_seconds);
  v_payload_hash text := public.security_hash_text(coalesce(p_payload::text, '{}'));
  v_secret text;
  v_signature text;
begin
  if v_actor_user_id is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  if v_rpc_name is null then
    raise exception 'rpc_name_required' using errcode = '22023';
  end if;

  select rpc_signature_secret into v_secret from public.security_runtime_config where id = true limit 1;
  if coalesce(v_secret, '') = '' then
    v_secret := public.security_hash_text(v_actor_user_id::text);
  end if;

  v_signature := encode(
    hmac(
      concat_ws('|', v_request_id, v_nonce, v_rpc_name, v_action_scope, v_actor_user_id::text, v_payload_hash, extract(epoch from v_expires_at)::bigint::text),
      v_secret,
      'sha256'
    ),
    'hex'
  );

  insert into public.rpc_nonce_registry (
    request_id,
    nonce,
    rpc_name,
    action_scope,
    actor_user_id,
    actor_role,
    payload_hash,
    request_signature,
    expires_at,
    status,
    metadata,
    first_seen_at,
    last_seen_at,
    created_at
  )
  values (
    v_request_id,
    v_nonce,
    v_rpc_name,
    v_action_scope,
    v_actor_user_id,
    public.current_security_actor_role(),
    v_payload_hash,
    v_signature,
    v_expires_at,
    'prepared',
    coalesce(p_metadata, '{}'::jsonb),
    timezone('utc', now()),
    timezone('utc', now()),
    timezone('utc', now())
  );

  perform public.log_security_metric('rpc_nonce_issued', 1, 'rpc_replay', v_actor_user_id, jsonb_build_object('rpc_name', v_rpc_name, 'action_scope', v_action_scope));

  request_id := v_request_id;
  nonce := v_nonce;
  expires_at := v_expires_at;
  request_signature := v_signature;
  return next;
exception
  when unique_violation then
    perform public.register_replay_attempt(null, v_request_id, v_nonce, v_rpc_name, v_action_scope, v_actor_user_id, 'duplicate_request_id_prepare', v_payload_hash, null, p_metadata);
    raise exception 'duplicate_request_id' using errcode = '23505';
end;
$$;

