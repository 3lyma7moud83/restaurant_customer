create or replace function public.record_security_event(
  p_event_key text,
  p_severity text default 'medium',
  p_actor_user_id uuid default auth.uid(),
  p_session_id text default null,
  p_device_fingerprint text default null,
  p_source_ip text default null,
  p_event_payload jsonb default '{}'::jsonb,
  p_related_request_id text default null,
  p_related_nonce text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
  v_key text := coalesce(nullif(trim(p_event_key), ''), 'security_event');
  v_severity text := public.normalize_security_severity(p_severity);
begin
  insert into public.security_events (
    event_key,
    severity,
    actor_user_id,
    actor_role,
    session_id,
    device_fingerprint,
    source_ip,
    event_payload,
    related_request_id,
    related_nonce,
    occurred_at
  )
  values (
    v_key,
    v_severity,
    p_actor_user_id,
    public.current_security_actor_role(),
    nullif(trim(coalesce(p_session_id, '')), ''),
    nullif(trim(coalesce(p_device_fingerprint, '')), ''),
    nullif(trim(coalesce(p_source_ip, '')), ''),
    coalesce(p_event_payload, '{}'::jsonb),
    nullif(trim(coalesce(p_related_request_id, '')), ''),
    nullif(trim(coalesce(p_related_nonce, '')), ''),
    timezone('utc', now())
  )
  returning id into v_id;

  perform public.log_security_metric(v_key, 1, 'security_event', p_actor_user_id, jsonb_build_object('severity', v_severity));
  return v_id;
end;
$$;

