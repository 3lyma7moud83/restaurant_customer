create or replace function public.evaluate_security_escalation(
  p_subject_kind text,
  p_subject_value text,
  p_event_key text,
  p_severity text default 'medium',
  p_event_payload jsonb default '{}'::jsonb,
  p_actor_user_id uuid default auth.uid()
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_subject_kind text := coalesce(nullif(trim(p_subject_kind), ''), 'user');
  v_subject_value text := coalesce(nullif(trim(p_subject_value), ''), 'unknown');
  v_event_key text := coalesce(nullif(trim(p_event_key), ''), 'security_event');
  v_severity text := public.normalize_security_severity(p_severity);
  v_delta integer;
  v_level integer;
  v_lock_seconds integer;
  v_row public.escalation_state%rowtype;
  v_now timestamptz := timezone('utc', now());
  v_alert_id uuid;
begin
  v_delta := case v_severity
    when 'low' then 1
    when 'medium' then 3
    when 'high' then 6
    when 'critical' then 10
    else 3
  end;

  if v_event_key like '%replay%' or v_event_key like '%abuse%' then
    v_delta := v_delta + 3;
  elsif v_event_key like '%poison%' then
    v_delta := v_delta + 4;
  elsif v_event_key like '%suspicious%' then
    v_delta := v_delta + 2;
  end if;

  insert into public.escalation_state (
    subject_kind,
    subject_value,
    score,
    last_event_key,
    last_event_at,
    metadata
  )
  values (
    v_subject_kind,
    v_subject_value,
    v_delta,
    v_event_key,
    v_now,
    coalesce(p_event_payload, '{}'::jsonb)
  )
  on conflict (subject_kind, subject_value)
  do update
    set
      score = public.escalation_state.score + excluded.score,
      last_event_key = excluded.last_event_key,
      last_event_at = excluded.last_event_at,
      metadata = coalesce(public.escalation_state.metadata, '{}'::jsonb) || excluded.metadata,
      updated_at = timezone('utc', now())
  returning * into v_row;

  v_level := case
    when v_row.score >= 50 then 4
    when v_row.score >= 30 then 3
    when v_row.score >= 18 then 2
    when v_row.score >= 10 then 1
    else 0
  end;

  v_lock_seconds := case v_level
    when 1 then 120
    when 2 then 600
    when 3 then 1800
    when 4 then 7200
    else 0
  end;

  update public.escalation_state
  set
    current_level = v_level,
    lockout_until = case
      when v_lock_seconds > 0 then greatest(coalesce(lockout_until, v_now), v_now + make_interval(secs => v_lock_seconds))
      else lockout_until
    end,
    cooldown_until = v_now + make_interval(secs => least(3600, greatest(60, v_row.score * 5))),
    updated_at = v_now
  where id = v_row.id
  returning * into v_row;

  v_alert_id := public.upsert_security_alert(
    'security_escalation',
    v_severity,
    v_subject_kind,
    v_subject_value,
    p_actor_user_id,
    null,
    jsonb_build_object('event_key', v_event_key, 'level', v_level, 'score', v_row.score)
  );

  insert into public.mitigation_actions (
    escalation_state_id,
    action_type,
    reason,
    action_payload,
    acted_by,
    acted_at
  )
  values (
    v_row.id,
    case when v_level >= 3 then 'temporary_lockout' else 'security_cooldown' end,
    format('Escalation level %s triggered by %s', v_level, v_event_key),
    jsonb_build_object('lockout_until', v_row.lockout_until, 'cooldown_until', v_row.cooldown_until, 'score', v_row.score),
    p_actor_user_id,
    v_now
  );

  perform public.log_security_metric('escalation_triggers', 1, 'security_escalation', p_actor_user_id, jsonb_build_object('level', v_level, 'score', v_row.score, 'alert_id', v_alert_id));

  return jsonb_build_object(
    'subject_kind', v_subject_kind,
    'subject_value', v_subject_value,
    'level', v_level,
    'score', v_row.score,
    'lockout_until', v_row.lockout_until,
    'cooldown_until', v_row.cooldown_until,
    'alert_id', v_alert_id
  );
end;
$$;

