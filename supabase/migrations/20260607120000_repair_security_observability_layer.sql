create or replace function public.normalize_security_severity(p_value text)
returns text
language plpgsql
immutable
as $$
declare
  v_value text := lower(coalesce(trim(p_value), 'medium'));
begin
  if v_value in ('low', 'medium', 'high', 'critical') then
    return v_value;
  end if;
  return 'medium';
end;
$$;

create or replace function public.security_hash_text(p_input text)
returns text
language sql
immutable
as $$
  select encode(extensions.digest(coalesce($1, ''), 'sha256'), 'hex');
$$;

create or replace function public.current_security_actor_role()
returns text
language plpgsql
stable
as $$
begin
  return lower(
    coalesce(
      nullif(trim(auth.jwt() ->> 'role'), ''),
      nullif(trim(current_setting('request.jwt.claim.role', true)), ''),
      current_user,
      'authenticated'
    )
  );
end;
$$;

create or replace function public.prevent_immutable_mutation()
returns trigger
language plpgsql
as $$
begin
  raise exception 'immutable_violation on %.%', tg_table_schema, tg_table_name
    using errcode = '42501';
end;
$$;

