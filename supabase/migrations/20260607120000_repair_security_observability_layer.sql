create or replace function public.prepare_rpc_nonce(
  p_rpc_name text,
  p_action_scope text default 'default',
  p_request_id text default null,
  p_payload jsonb default '{}'::jsonb,
  p_valid_for_seconds integer default 120,
  p_metadata jsonb default '{}'::jsonb
)
returns table (
  request_id text,
  nonce text,
  expires_at timestamptz,
  request_signature text
)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_rpc_name text := nullif(trim(p_rpc_name), '');
  v_action_scope text := coalesce(nullif(trim(p_action_scope), ''), 'default');
  v_actor_user_id uuid := auth.uid();
  v_request_id text := coalesce(nullif(trim(p_request_id), ''), extensions.gen_random_uuid()::text);
  v_nonce text := encode(extensions.gen_random_bytes(18), 'hex');
  v_valid_for_seconds integer := greatest(30, least(coalesce(p_valid_for_seconds, 120), 600));
  v_expires_at timestamptz := timezone('utc', now()) + make_interval(secs => v_valid_for_seconds);
  v_payload_hash text := public.security_hash_text(coalesce(p_payload::text, '{}'));
  v_secret text;
  v_signature text;
begin
  if v_actor_user_id is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  if v_rpc_name is null then
    raise exception 'rpc_name_required' using errcode = '22023';
  end if;

  select rpc_signature_secret
  into v_secret
  from public.security_runtime_config
  where id = true
  limit 1;

  if coalesce(v_secret, '') = '' then
    v_secret := public.security_hash_text(v_actor_user_id::text);
  end if;

  v_signature := encode(
    extensions.hmac(
      concat_ws('|', v_request_id, v_nonce, v_rpc_name, v_action_scope, v_actor_user_id::text, v_payload_hash, extract(epoch from v_expires_at)::bigint::text),
      v_secret,
      'sha256'
    ),
    'hex'
  );

  insert into public.rpc_nonce_registry (
    request_id,
    nonce,
    rpc_name,
    action_scope,
    actor_user_id,
    actor_role,
    payload_hash,
    request_signature,
    expires_at,
    status,
    metadata,
    first_seen_at,
    last_seen_at,
    created_at
  )
  values (
    v_request_id,
    v_nonce,
    v_rpc_name,
    v_action_scope,
    v_actor_user_id,
    public.current_security_actor_role(),
    v_payload_hash,
    v_signature,
    v_expires_at,
    'prepared',
    coalesce(p_metadata, '{}'::jsonb),
    timezone('utc', now()),
    timezone('utc', now()),
    timezone('utc', now())
  );

  perform public.log_security_metric('rpc_nonce_issued', 1, 'rpc_replay', v_actor_user_id, jsonb_build_object('rpc_name', v_rpc_name, 'action_scope', v_action_scope));

  request_id := v_request_id;
  nonce := v_nonce;
  expires_at := v_expires_at;
  request_signature := v_signature;
  return next;
exception
  when unique_violation then
    perform public.register_replay_attempt(null, v_request_id, v_nonce, v_rpc_name, v_action_scope, v_actor_user_id, 'duplicate_request_id_prepare', v_payload_hash, null, p_metadata);
    raise exception 'duplicate_request_id' using errcode = '23505';
end;
$$;

create or replace function public.verify_and_consume_rpc_nonce(
  p_rpc_name text,
  p_action_scope text,
  p_request_id text,
  p_nonce text,
  p_request_signature text,
  p_payload jsonb default '{}'::jsonb,
  p_raise_on_failure boolean default true,
  p_actor_user_id uuid default auth.uid(),
  p_metadata jsonb default '{}'::jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_rpc_name text := nullif(trim(p_rpc_name), '');
  v_action_scope text := coalesce(nullif(trim(p_action_scope), ''), 'default');
  v_request_id text := nullif(trim(p_request_id), '');
  v_nonce text := nullif(trim(p_nonce), '');
  v_signature text := nullif(trim(p_request_signature), '');
  v_payload_hash text := public.security_hash_text(coalesce(p_payload::text, '{}'));
  v_actor_user_id uuid := coalesce(p_actor_user_id, auth.uid());
  v_secret text;
  v_expected_signature text;
  v_now timestamptz := timezone('utc', now());
  v_reason text;
  v_row public.rpc_nonce_registry%rowtype;
begin
  if v_actor_user_id is null then
    if p_raise_on_failure then
      raise exception 'not_authenticated' using errcode = '42501';
    end if;
    return false;
  end if;

  if v_rpc_name is null or v_request_id is null or v_nonce is null or v_signature is null then
    v_reason := 'missing_nonce_arguments';
    perform public.register_replay_attempt(null, v_request_id, v_nonce, v_rpc_name, v_action_scope, v_actor_user_id, v_reason, v_payload_hash, v_signature, p_metadata);
    if p_raise_on_failure then
      raise exception 'rpc_replay_guard_violation:%', v_reason using errcode = '42501';
    end if;
    return false;
  end if;

  select *
  into v_row
  from public.rpc_nonce_registry
  where request_id = v_request_id
  limit 1;

  if not found then
    v_reason := 'nonce_not_found';
  elsif coalesce(v_row.nonce, '') <> v_nonce then
    v_reason := 'nonce_mismatch';
  elsif coalesce(v_row.rpc_name, '') <> v_rpc_name then
    v_reason := 'rpc_name_mismatch';
  elsif coalesce(v_row.action_scope, '') <> v_action_scope then
    v_reason := 'action_scope_mismatch';
  elsif v_row.actor_user_id is distinct from v_actor_user_id then
    v_reason := 'actor_mismatch';
  elsif v_row.status = 'consumed' then
    v_reason := 'already_consumed';
  elsif v_row.status = 'rejected' then
    v_reason := 'already_rejected';
  elsif v_row.status = 'expired' or v_row.expires_at <= v_now then
    v_reason := 'expired_nonce';
  elsif coalesce(v_row.payload_hash, '') <> v_payload_hash then
    v_reason := 'payload_hash_mismatch';
  end if;

  if v_reason is null then
    select rpc_signature_secret
    into v_secret
    from public.security_runtime_config
    where id = true
    limit 1;

    if coalesce(v_secret, '') = '' then
      v_secret := public.security_hash_text(v_actor_user_id::text);
    end if;

    v_expected_signature := encode(
      extensions.hmac(
        concat_ws('|', v_row.request_id, v_row.nonce, v_row.rpc_name, v_row.action_scope, v_row.actor_user_id::text, v_row.payload_hash, extract(epoch from v_row.expires_at)::bigint::text),
        v_secret,
        'sha256'
      ),
      'hex'
    );

    if v_expected_signature <> v_signature then
      v_reason := 'invalid_signature';
    end if;
  end if;

  if v_reason is not null then
    if v_row.id is not null then
      update public.rpc_nonce_registry
      set
        status = case when v_reason = 'expired_nonce' then 'expired' else 'rejected' end,
        last_seen_at = v_now
      where id = v_row.id;
    end if;

    perform public.register_replay_attempt(v_row.id, v_request_id, v_nonce, v_rpc_name, v_action_scope, v_actor_user_id, v_reason, v_payload_hash, v_signature, p_metadata);

    if p_raise_on_failure then
      raise exception 'rpc_replay_guard_violation:%', v_reason using errcode = '42501';
    end if;
    return false;
  end if;

  update public.rpc_nonce_registry
  set status = 'consumed', consumed_at = v_now, last_seen_at = v_now
  where id = v_row.id;

  perform public.append_immutable_audit('rpc_nonce_consumed', v_rpc_name, 'rpc', v_rpc_name, jsonb_build_object('request_id', v_request_id, 'nonce', v_nonce, 'action_scope', v_action_scope), 'rpc_guard', v_actor_user_id, public.current_security_actor_role());
  perform public.log_security_metric('rpc_nonce_consumed', 1, 'rpc_replay', v_actor_user_id, jsonb_build_object('rpc_name', v_rpc_name));

  return true;
end;
$$;

create or replace function public.security_count_since(
  p_table_name text,
  p_timestamp_column text,
  p_since timestamptz,
  p_where_sql text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_table regclass := to_regclass(p_table_name);
  v_count bigint := 0;
  v_sql text;
begin
  if v_table is null then
    return 0;
  end if;

  v_sql := format(
    'select count(*) from %s where %I >= $1',
    v_table,
    p_timestamp_column
  );

  if nullif(trim(coalesce(p_where_sql, '')), '') is not null then
    v_sql := v_sql || ' and (' || p_where_sql || ')';
  end if;

  execute v_sql into v_count using p_since;
  return coalesce(v_count, 0);
exception
  when undefined_table or undefined_column then
    return 0;
end;
$$;

create or replace function public.security_observability_dashboard(
  p_lookback interval default interval '24 hours'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_since timestamptz := timezone('utc', now()) - coalesce(p_lookback, interval '24 hours');
  v_rpc_total bigint := 0;
  v_rpc_rejections bigint := 0;
begin
  v_rpc_total := public.security_count_since('public.rpc_nonce_registry', 'created_at', v_since);
  v_rpc_rejections := public.security_count_since('public.replay_attempt_logs', 'detected_at', v_since);

  return jsonb_build_object(
    'lookback_since', v_since,
    'generated_at', timezone('utc', now()),
    'replay_attempts', v_rpc_rejections,
    'suspicious_sessions', public.security_count_since('public.suspicious_sessions', 'detected_at', v_since),
    'escalation_attempts', public.security_count_since('public.security_metrics', 'recorded_at', v_since, 'metric_key = ''escalation_triggers'''),
    'realtime_auth_failures', public.security_count_since('public.security_metrics', 'recorded_at', v_since, 'metric_key in (''auth_channel_kills'', ''realtime_auth_revalidation_failures'')'),
    'zombie_cleanup_count', public.security_count_since('public.customer_stability_metrics', 'created_at', v_since, 'metric_key = ''stale_realtime_subscriptions'''),
    'dlq_poison_count', public.security_count_since('public.poison_payload_registry', 'last_seen_at', v_since),
    'revoked_sessions', public.security_count_since('public.revoked_sessions', 'revoked_at', v_since),
    'abuse_attempts', public.security_count_since('public.admin_action_limits', 'attempted_at', v_since, 'allowed = false'),
    'rpc_rejection_rates', jsonb_build_object(
      'rejections', v_rpc_rejections,
      'total', v_rpc_total,
      'percentage', case when v_rpc_total > 0 then round((v_rpc_rejections::numeric / v_rpc_total::numeric) * 100, 2) else 0 end
    )
  );
end;
$$;

